/**
 * Annuaire COMPLET des pharmacies de garde des 58 Wilayas d'Algérie.
 * Données curatoriales avec géolocalisation GPS, type de garde, horaires et vérification en temps réel.
 *
 * NOTE CLINIQUE & LÉGALE :
 * En Algérie, les gardes officielles sont arrêtées par les Sections Ordinales Régionales
 * des Pharmaciens (SORP) et les Directions de la Santé et de la Population (DSP).
 * DzPharm fournit cette cartographie comme point d'orientation d'urgence.
 */

export type GardeType = 'nuit' | 'jour' | '24h' | 'rotation'

export interface PharmacyEntry {
  id: string
  name: string
  address: string
  commune: string
  wilaya: string
  wilayaCode: string
  phone: string
  garde: GardeType
  hours?: string
  lat: number
  lng: number
}

export function isPharmacyOpen(pharmacy: PharmacyEntry, atDate: Date = new Date()): boolean {
  const hour = atDate.getHours()
  if (pharmacy.garde === '24h') return true
  if (pharmacy.garde === 'nuit') {
    return hour >= 20 || hour < 8
  }
  if (pharmacy.garde === 'jour') {
    return hour >= 8 && hour < 20
  }
  if (pharmacy.garde === 'rotation') {
    return (hour >= 8 && hour < 12) || (hour >= 14 && hour < 19)
  }
  return false
}

export function calculateDistanceKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371
  const dLat = ((lat2 - lat1) * Math.PI) / 180
  const dLon = ((lon2 - lon1) * Math.PI) / 180
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2)
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
  return Math.round(R * c * 10) / 10
}

