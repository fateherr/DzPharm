/** Wilayas couvertes par l'annuaire (les 58 wilayas d'Algérie), avec leur nombre de pharmacies. */
export const PHARMACY_WILAYAS: Array<{ wilaya: string; wilayaCode: string; count: number }> = (() => {
  const map = new Map<string, { wilayaCode: string; count: number }>()
  for (const p of PHARMACY_DIRECTORY) {
    const existing = map.get(p.wilaya)
    if (existing) {
      existing.count += 1
    } else {
      map.set(p.wilaya, { wilayaCode: p.wilayaCode, count: 1 })
    }
  }
  return [...map.entries()]
    .map(([wilaya, data]) => ({ wilaya, wilayaCode: data.wilayaCode, count: data.count }))
    .sort((a, b) => parseInt(a.wilayaCode, 10) - parseInt(b.wilayaCode, 10))
})()
